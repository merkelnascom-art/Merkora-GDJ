import {
  selectNextDiscoveryQuestion,
  type DiscoveryQuestionSelection,
} from "./universal-project-discovery";
import type { ConversationMessage } from "./assistant/merkora-conversation";
import type { UniversalProjectUnderstanding } from "./universal-project-understanding";

export const CLIENT_JOURNEY_STAGES = [
  "welcome",
  "understanding",
  "analysis",
  "proposals",
  "concept",
  "personalization",
  "validation",
  "realization",
] as const;

export type ClientJourneyStage = (typeof CLIENT_JOURNEY_STAGES)[number];

export type ClientJourneyState = {
  projectId: string | null;
  stage: ClientJourneyStage;
  completedStages: ClientJourneyStage[];
  pendingQuestion: string | null;
};

export type ClientJourneyDecisions = {
  /** IDs explicitly selected by the client; recommendations are not selections. */
  selectedProposalIds: string[];
  /** True only after the client explicitly continues from the proposals step. */
  proposalSelectionConfirmed: boolean;
  /** A concept selected by the client, not merely generated by the system. */
  selectedConceptId: string | null;
  /** Explicit approval of the concept/design by the client. */
  designValidated: boolean;
};

export type ClientJourneyInput = {
  projectId: string | null;
  currentStage: ClientJourneyStage;
  discovery?: DiscoveryQuestionSelection | null;
  decisions: ClientJourneyDecisions;
  /** Commercial state is deliberately not used to gate design validation or realization. */
  commercial?: { quoteAccepted?: boolean; paymentCompleted?: boolean };
};

export function createClientJourneyState(projectId: string | null): ClientJourneyState {
  const normalizedId = typeof projectId === "string" ? projectId.trim() : "";
  return {
    projectId: normalizedId || null,
    stage: normalizedId ? "understanding" : "welcome",
    completedStages: [],
    pendingQuestion: null,
  };
}

export function getDiscoveryQuestionSelection(
  analysis: UniversalProjectUnderstanding,
  history: ConversationMessage[],
): DiscoveryQuestionSelection {
  return selectNextDiscoveryQuestion(analysis, history);
}

function hasReadyDiscovery(discovery: DiscoveryQuestionSelection | null | undefined): boolean {
  return Boolean(
    discovery?.readyForSolutionReview &&
      discovery.remainingGaps.length === 0 &&
      discovery.contradictions.length === 0 &&
      discovery.evaluation.status === "reviewable" &&
      discovery.evaluation.solutionReviewAllowed &&
      discovery.evaluation.blockingStages.length === 0 &&
      discovery.evaluation.blockingQuestions.length === 0,
  );
}

function hasSelectedConcept(input: ClientJourneyInput): boolean {
  return typeof input.decisions.selectedConceptId === "string" &&
    input.decisions.selectedConceptId.trim().length > 0;
}

export function canEnterJourneyStage(
  stage: ClientJourneyStage,
  input: ClientJourneyInput,
): boolean {
  if (stage === "welcome") return true;
  if (!input.projectId?.trim()) return false;

  switch (stage) {
    case "understanding":
      return true;
    case "analysis":
    case "proposals":
      return hasReadyDiscovery(input.discovery);
    case "concept":
      return input.decisions.proposalSelectionConfirmed &&
        input.decisions.selectedProposalIds.length > 0;
    case "personalization":
    case "validation":
      return hasSelectedConcept(input);
    case "realization":
      return hasSelectedConcept(input) && input.decisions.designValidated;
  }
}

export function getNextJourneyStage(input: ClientJourneyInput): ClientJourneyStage {
  const currentIndex = CLIENT_JOURNEY_STAGES.indexOf(input.currentStage);
  if (currentIndex < 0) return "welcome";

  for (let index = currentIndex + 1; index < CLIENT_JOURNEY_STAGES.length; index += 1) {
    const candidate = CLIENT_JOURNEY_STAGES[index];
    if (canEnterJourneyStage(candidate, input)) return candidate;
    return input.currentStage;
  }

  return input.currentStage;
}

export function restoreClientJourneyState(value: unknown): ClientJourneyState {
  if (!value || typeof value !== "object") return createClientJourneyState(null);

  const candidate = value as Record<string, unknown>;
  const projectId = typeof candidate.projectId === "string" ? candidate.projectId.trim() : "";
  if (!projectId) return createClientJourneyState(null);

  const stage = CLIENT_JOURNEY_STAGES.includes(candidate.stage as ClientJourneyStage) && candidate.stage !== "welcome"
    ? (candidate.stage as ClientJourneyStage)
    : "understanding";
  const completedStages = Array.isArray(candidate.completedStages)
    ? candidate.completedStages.filter((item): item is ClientJourneyStage =>
        typeof item === "string" && CLIENT_JOURNEY_STAGES.includes(item as ClientJourneyStage),
      )
    : [];

  return {
    projectId,
    stage,
    completedStages: [...new Set(completedStages)],
    pendingQuestion: typeof candidate.pendingQuestion === "string" ? candidate.pendingQuestion : null,
  };
}
