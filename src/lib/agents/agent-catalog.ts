function defineAgent(
  input: Omit<AgentDefinition, "implementationStatus">,
): AgentDefinition {
  return {
    ...input,
    implementationStatus: "catalog_only",
  };
}

function definePole(
  id: AgentPoleId,
  name: string,
  objective: string,
  description: string,
  agents: readonly AgentDefinition[],
): AgentPoleDefinition {
  if (agents.length !== 5) {
    throw new Error(`Le pôle ${id} doit contenir exactement cinq agents.`);
  }
  return { id, name, objective, description, agents };
}

