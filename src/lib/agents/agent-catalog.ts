export type AgentPoleId =
  | "intelligence"
  | "conception"
  | "fabrication"
  | "controle"
  | "exploitation"
  | "relation_client"
  | "gestion_administration";

export type AgentDefinition = {
  readonly id: string;
  readonly name: string;
  readonly poleId: AgentPoleId;
  readonly mission: string;
  readonly responsibilities: readonly string[];
  readonly activationTriggers: readonly string[];
  readonly inputs: readonly string[];
  readonly outputs: readonly string[];
  /**
   * Conceptual tool domains for architecture and planning.
   * These are not provider capabilities or granted permissions.
   */
  readonly suggestedToolDomains: readonly string[];
  readonly permissionBoundaries: readonly string[];
  readonly acceptanceCriteria: readonly string[];
  readonly verificationMethods: readonly string[];
  readonly failureHandling: readonly string[];
  readonly implementationStatus: "catalog_only";
};

export type AgentPoleDefinition = {
  readonly id: AgentPoleId;
  readonly name: string;
  readonly objective: string;
  readonly description: string;
  readonly agents: readonly AgentDefinition[];
};

